// Generates every logo file from ONE drawing of the brand mark (the "Tj"
// road monogram: a T whose stem runs as a road into a J, with dashed
// center lines). Re-run after changing MARK below:
//   node deploy/make-logo.js
// Writes the SVGs under frontend/assets/icons/; the PNG sizes (favicon,
// touch icons, og-image) are rendered from these SVGs in a browser
// (see deploy/README or the commit that added this file).
// Colors are the site palette (assets/css/tokens.css): forest #2C5745,
// cream #EBE3A7, orange #EB7D00, olive #2E2910.
const fs = require('fs');
const path = require('path');
const out = path.join(__dirname, '..', 'frontend', 'assets', 'icons');

// The mark in its own 800×800 box (from the concept artwork).
// v2 (2026-10-22): the owner's refined concept — the second bar flows into
// the stem with a curve, a thicker road, a V-shaped inside to the U.
// Optically centered, not by its box: the wide bars make the shape top-heavy
// (its center of mass sits ~4% above and ~2% right of the box center), so the
// box is shifted halfway toward that — measured on the rendered badge.
const MARK_VIEWBOX = '232 214 830 830';
// The whole drawing (x 275–1002, y 258–1066) fits this one; used where the
// mark stands alone (logo-mark.svg). Inside the badges the shifted box above is
// used with overflow visible, so nothing is ever cut off.
const MARK_VIEWBOX_FULL = '220 245 830 830';
function mark(ink, dash) {
  const road = 'M432 470 V760 Q432 830 520 895 L640 975 Q690 1005 740 975 L860 895 Q926 830 926 760 V450';
  return [
    `<rect x="275" y="258" width="710" height="92" rx="46" fill="${ink}"/>`,
    `<rect x="275" y="382" width="553" height="93" rx="46.5" fill="${ink}"/>`,
    `<path d="${road}" fill="none" stroke="${ink}" stroke-width="152" stroke-linejoin="round"/>`,
    `<circle cx="926" cy="450" r="76" fill="${ink}"/>`,
    // the curves where the bar meets the stem (outside) and the inside corner
    `<path d="M318 474 L357 474 L357 520 Q357 474 318 474 Z" fill="${ink}"/>`,
    `<path d="M507 474 L552 474 Q507 474 507 518 Z" fill="${ink}"/>`,
    `<path d="M432 528 V760 Q432 830 520 895 L640 975 Q690 1005 740 975 L860 895 Q926 830 926 760 V468" fill="none" stroke="${dash}" stroke-width="15" stroke-linecap="round" stroke-dasharray="74 52"/>`,
  ].join('');
}
// A mark on a circle, in a 64×64 box; `scale` = the mark's share of the circle.
function badge(circle, ink, dash, scale, note) {
  const s = 64 * scale, o = (64 - s) / 2;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">
  <!-- ${note} Generated by deploy/make-logo.js; edit the drawing there. -->
  <circle cx="32" cy="32" r="32" fill="${circle}"/>
  <svg x="${o}" y="${o}" width="${s}" height="${s}" viewBox="${MARK_VIEWBOX}" overflow="visible">${mark(ink, dash)}</svg>
</svg>
`;
}

const FOREST = '#2C5745', CREAM = '#EBE3A7', ORANGE = '#EB7D00', OLIVE = '#2E2910';
const files = {
  'logo.svg': badge(FOREST, CREAM, ORANGE, 0.56, 'The brand badge used everywhere (app banner, splash, favicon, about/share).'),
  'favicon.svg': badge(FOREST, CREAM, ORANGE, 0.56, 'Favicon: same as logo.svg.'),
  'logo-header.svg': badge(FOREST, CREAM, ORANGE, 0.58, 'Marketing header, light theme (mark a little larger).'),
  'logo-header-dark.svg': badge(ORANGE, OLIVE, CREAM, 0.58, 'Marketing header, dark theme: orange circle, olive mark.'),
  'logo-mark.svg': `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${MARK_VIEWBOX_FULL}">${mark(OLIVE, ORANGE)}</svg>\n`,
  'og-image.svg': `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1200 630">
  <!-- Link preview image. Generated by deploy/make-logo.js. -->
  <rect width="1200" height="630" fill="${OLIVE}"/>
  <circle cx="240" cy="315" r="130" fill="${FOREST}"/>
  <svg x="160" y="235" width="160" height="160" viewBox="${MARK_VIEWBOX}" overflow="visible">${mark(CREAM, ORANGE)}</svg>
  <text x="430" y="290" font-family="Tahoma, Arial, sans-serif" font-size="84" font-weight="800" fill="${ORANGE}">Toojibee</text>
  <text x="430" y="370" font-family="Tahoma, Arial, sans-serif" font-size="40" fill="${CREAM}">توجیبی · تقویم و برنامه‌ریزی روزانه</text>
</svg>
`,
};
for (const [name, svg] of Object.entries(files)) fs.writeFileSync(path.join(out, name), svg);
console.log('wrote', Object.keys(files).join(', '));
