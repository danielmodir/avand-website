// Generates every logo file from ONE drawing of the brand mark (the "Tj"
// road monogram: a T whose stem runs as a road into a J, with dashed
// center lines). Re-run after changing MARK below:
//   node deploy/make-logo.js
// Writes the SVGs under frontend/assets/icons/; the PNG sizes (favicon,
// touch icons, og-image) are rendered from these SVGs in a browser
// (see deploy/README or the commit that added this file).
// Colors are the site palette (assets/css/tokens.css): forest #2C5745,
// cream #EBE3A7, orange #EB7D00, olive #2E2910.
const fs = require('fs');
const path = require('path');
const out = path.join(__dirname, '..', 'frontend', 'assets', 'icons');

// The mark in its own 800×800 box (from the concept artwork).
const MARK_VIEWBOX = '18 131 800 800';
function mark(ink, dash) {
  const road = 'M256 340 V650 L420 770 Q463 795 506 770 L671 650 V370';
  return [
    `<rect x="35" y="207" width="765" height="75" rx="37.5" fill="${ink}"/>`,
    `<rect x="35" y="307" width="540" height="76" rx="38" fill="${ink}"/>`,
    `<path d="${road}" fill="none" stroke="${ink}" stroke-width="127" stroke-linejoin="round"/>`,
    `<circle cx="671" cy="370" r="63.5" fill="${ink}"/>`,
    `<path d="M256 430 V650 L420 770 Q463 795 506 770 L671 650 V385" fill="none" stroke="${dash}" stroke-width="12" stroke-linecap="round" stroke-dasharray="58 46"/>`,
  ].join('');
}
// A mark on a circle, in a 64×64 box; `scale` = the mark's share of the circle.
function badge(circle, ink, dash, scale, note) {
  const s = 64 * scale, o = (64 - s) / 2;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">
  <!-- ${note} Generated by deploy/make-logo.js; edit the drawing there. -->
  <circle cx="32" cy="32" r="32" fill="${circle}"/>
  <svg x="${o}" y="${o}" width="${s}" height="${s}" viewBox="${MARK_VIEWBOX}">${mark(ink, dash)}</svg>
</svg>
`;
}

const FOREST = '#2C5745', CREAM = '#EBE3A7', ORANGE = '#EB7D00', OLIVE = '#2E2910';
const files = {
  'logo.svg': badge(FOREST, CREAM, ORANGE, 0.62, 'The brand badge used everywhere (app banner, splash, favicon, about/share).'),
  'favicon.svg': badge(FOREST, CREAM, ORANGE, 0.62, 'Favicon: same as logo.svg.'),
  'logo-header.svg': badge(FOREST, CREAM, ORANGE, 0.7, 'Marketing header, light theme (mark a little larger).'),
  'logo-header-dark.svg': badge(ORANGE, OLIVE, CREAM, 0.7, 'Marketing header, dark theme: orange circle, olive mark.'),
  'logo-mark.svg': `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${MARK_VIEWBOX}">${mark(OLIVE, ORANGE)}</svg>\n`,
  'og-image.svg': `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1200 630">
  <!-- Link preview image. Generated by deploy/make-logo.js. -->
  <rect width="1200" height="630" fill="${OLIVE}"/>
  <circle cx="240" cy="315" r="130" fill="${FOREST}"/>
  <svg x="160" y="235" width="160" height="160" viewBox="${MARK_VIEWBOX}">${mark(CREAM, ORANGE)}</svg>
  <text x="430" y="290" font-family="Tahoma, Arial, sans-serif" font-size="84" font-weight="800" fill="${ORANGE}">Toojibee</text>
  <text x="430" y="370" font-family="Tahoma, Arial, sans-serif" font-size="40" fill="${CREAM}">توجیبی · تقویم و برنامه‌ریزی روزانه</text>
</svg>
`,
};
for (const [name, svg] of Object.entries(files)) fs.writeFileSync(path.join(out, name), svg);
console.log('wrote', Object.keys(files).join(', '));
