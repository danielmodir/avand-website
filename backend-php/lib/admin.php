/* ---- managing admins (admins.manage) ---- */

function tj_admin_public(array $a): array {
    return [
        'id' => $a['public_id'], 'email' => $a['email'], 'is_owner' => (int)$a['is_owner'] === 1,
        'permissions' => tj_admin_perms($a),
        'status' => $a['disabled_at'] !== null ? 'disabled' : ($a['password_hash'] === '' ? 'invited' : 'active'),
        'last_login_at' => $a['last_login_at'], 'created_at' => $a['created_at'],
    ];
}

function tj_admin_list(): void {
    tj_admin_require('admins.manage');
    $rows = tj_db()->query('SELECT * FROM tj_admins ORDER BY is_owner DESC, created_at')->fetchAll();
    tj_json(['items' => array_map('tj_admin_public', $rows), 'all_permissions' => TJ_ADMIN_PERMISSIONS]);
}

function tj_admin_new_invite(): string {
    return implode('-', str_split(tj_random_code(16), 4));
}

function tj_admin_create(): void {
    $me = tj_admin_require('admins.manage');
    $b = tj_body();
    $email = strtolower(tj_str($b, 'email', 254));
    if (!tj_valid_email($email)) tj_fail(400, 'validation_error', ['fields' => ['email' => ['invalid']]]);
    $perms = tj_admin_clean_perms($b['permissions'] ?? []);
    // Nobody hands out access they don't have themselves.
    if (array_diff($perms, tj_admin_perms($me))) tj_fail(403, 'forbidden');
    $q = tj_db()->prepare('SELECT 1 FROM tj_admins WHERE email = ?');
    $q->execute([$email]);
    if ($q->fetch()) tj_fail(409, 'email_taken');
    $code = tj_admin_new_invite();
    tj_db()->prepare('INSERT INTO tj_admins (public_id, email, permissions, invite_hash, invite_expires, created_by, created_at) VALUES (?, ?, ?, ?, ?, ?, ?)')
        ->execute([tj_new_public_id(), $email, json_encode($perms), tj_hash(str_replace('-', '', $code)), tj_now(TJ_ADMIN_INVITE_TTL), $me['id'], tj_now()]);
    tj_admin_audit((int)$me['id'], 'admin_invited', $email . ' [' . implode(', ', $perms) . ']');
    // The code is shown once, to the inviting admin, and stored only as a hash.
    tj_json(['invite_code' => $code, 'expires_in' => TJ_ADMIN_INVITE_TTL], 201);
}

function tj_admin_update(string $publicId): void {
    $me = tj_admin_require('admins.manage');
    $a = tj_admin_find($publicId);
    if ((int)$a['is_owner'] === 1) tj_fail(403, 'owner_locked');
    if ((int)$a['id'] === (int)$me['id']) tj_fail(403, 'not_yourself');
    $b = tj_body();
    $db = tj_db();
    $changes = [];
    if (array_key_exists('permissions', $b)) {
        $perms = tj_admin_clean_perms($b['permissions']);
        if (array_diff($perms, tj_admin_perms($me))) tj_fail(403, 'forbidden');
        $db->prepare('UPDATE tj_admins SET permissions = ? WHERE id = ?')->execute([json_encode($perms), $a['id']]);
        $changes[] = 'permissions=[' . implode(', ', $perms) . ']';
    }
    if (array_key_exists('disabled', $b)) {
        $off = (bool)$b['disabled'];
        $db->prepare('UPDATE tj_admins SET disabled_at = ? WHERE id = ?')->execute([$off ? tj_now() : null, $a['id']]);
        if ($off) tj_admin_end_sessions((int)$a['id']);
        $changes[] = $off ? 'disabled' : 'enabled';
    }
    if (!empty($b['new_invite']) && $a['password_hash'] === '') {
        $code = tj_admin_new_invite();
        $db->prepare('UPDATE tj_admins SET invite_hash = ?, invite_expires = ? WHERE id = ?')
            ->execute([tj_hash(str_replace('-', '', $code)), tj_now(TJ_ADMIN_INVITE_TTL), $a['id']]);
        $changes[] = 'new invite';
    }
    tj_admin_audit((int)$me['id'], 'admin_updated', $a['email'] . ': ' . implode('; ', $changes));
    tj_json(['admin' => tj_admin_public(tj_admin_find($publicId))] + (isset($code) ? ['invite_code' => $code] : []));
}

function tj_admin_remove(string $publicId): void {
    $me = tj_admin_require('admins.manage');
    $a = tj_admin_find($publicId);
    if ((int)$a['is_owner'] === 1) tj_fail(403, 'owner_locked');
    if ((int)$a['id'] === (int)$me['id']) tj_fail(403, 'not_yourself');
    tj_db()->prepare('DELETE FROM tj_admins WHERE id = ?')->execute([$a['id']]); // sessions go with it
    tj_admin_audit((int)$me['id'], 'admin_removed', $a['email']);
    tj_json(['ok' => true]);
}
