<?php
/* Admin panel API (/api/v1/admin/*) and its security.
 *
 * - Hidden address: the panel lives at https://toojibee.ir/<panel_slug>/,
 *   a random slug generated on the server into ~/toojibee-admin.php
 *   (outside the web root and outside git). Every admin API call must
 *   carry that slug (X-TJ-Panel header); without it the API answers
 *   404 like any unknown path, so the panel can't be found by probing.
 * - No sign-up: the first admin (the owner, every permission) is
 *   created with a one-time setup code from the same file, read in
 *   cPanel's File Manager; after that, setup is closed for good.
 * - More admins: an admin with admins.manage adds one by email and ticks
 *   their permissions; the new admin gets a one-time invite code (48 h)
 *   and chooses their own password, so nobody knows anyone else's.
 * - Password only (owner's choice), so: 12+ characters, bcrypt, a lock
 *   after 5 wrong tries (15 min), per-IP and per-address rate limits,
 *   the same answer and timing for unknown addresses.
 * - Session: random token in a __Host- cookie (HttpOnly, Secure,
 *   SameSite=Strict), stored only as SHA-256; 30 min idle, 8 h at most;
 *   ended at once when the admin is disabled or removed. State-changing
 *   calls also need an X-CSRF-Token derived from it and a same-origin
 *   Origin header.
 * - Every sign-in (good or bad), setup, invite and change goes to an
 *   append-only audit log.
 */
declare(strict_types=1);

const TJ_ADMIN_IDLE = 1800;          // 30 minutes without activity
const TJ_ADMIN_MAX_AGE = 8 * 3600;   // then sign in again regardless
const TJ_ADMIN_MIN_PASSWORD = 12;
const TJ_ADMIN_MAX_FAILS = 5;
const TJ_ADMIN_LOCK = 900;           // 15 minutes
const TJ_ADMIN_INVITE_TTL = 48 * 3600;
const TJ_ADMIN_COOKIE = '__Host-tj_admin';

/* What an admin can be allowed to do. The panel shows a checkbox for
 * each; tools that don't exist yet are listed so access can be planned. */
const TJ_ADMIN_PERMISSIONS = [
    'stats.view',       // numbers: users, sign-ups, sessions
    'users.view',       // see accounts (no task or period content)
    'users.manage',     // suspend, sign out, delete accounts
    'content.manage',   // site header, images, texts
    'articles.review',  // approve or reject articles
    'system.view',      // database tables, disk, memory, server
    'audit.view',       // the admins' activity log
    'admins.manage',    // add admins, change their access, remove them
];

function tj_admin_file(): string {
    return getenv('TJ_ADMIN_FILE') ?: tj_home() . '/toojibee-admin.php';
}

function tj_admin_write_file(array $s): void {
    $url = 'https://' . ($_SERVER['HTTP_HOST'] ?? 'toojibee.ir') . '/' . $s['panel_slug'] . '/';
    $php = "<?php\n// Toojibee admin panel. Generated by the API; keep it private, never commit it.\n"
         . "// Panel address: $url\n"
         . (isset($s['setup_code']) ? "// One-time setup code (for creating the first admin): {$s['setup_code']}\n" : "// Setup is done; the setup code has been removed.\n")
         . 'return ' . var_export($s, true) . ";\n";
    if (@file_put_contents(tj_admin_file(), $php, LOCK_EX) === false) tj_fail(500, 'admin_file_unwritable');
    @chmod(tj_admin_file(), 0600);
}

function tj_admin_settings(): array {
    static $s = null;
    if ($s !== null) return $s;
    if (!is_file(tj_admin_file())) {
        tj_admin_write_file([
            'panel_slug' => 'p-' . strtolower(tj_random_code(24)),
            'setup_code' => implode('-', str_split(tj_random_code(20), 5)),
        ]);
    }
    $s = require tj_admin_file();
    return $s;
}

/* The X-TJ-Panel header must match the slug, else: not found. */
function tj_admin_gate(): void {
    $given = (string)($_SERVER['HTTP_X_TJ_PANEL'] ?? '');
    if ($given === '' || !hash_equals(tj_admin_settings()['panel_slug'], $given)) tj_fail(404, 'not_found');
}

function tj_admin_audit(?int $adminId, string $action, string $detail = ''): void {
    tj_db()->prepare('INSERT INTO tj_admin_audit (admin_id, action, detail, ip, created_at) VALUES (?, ?, ?, ?, ?)')
        ->execute([$adminId, $action, substr($detail, 0, 500), tj_client_ip(), tj_now()]);
}

function tj_admin_password_problems(string $pw): array {
    $r = [];
    if ((function_exists('mb_strlen') ? mb_strlen($pw, 'UTF-8') : strlen($pw)) < TJ_ADMIN_MIN_PASSWORD) $r[] = 'too_short';
    if (!preg_match('/\p{L}/u', $pw) || !preg_match('/[^\p{L}]/u', $pw)) $r[] = 'needs_mix';
    if (strlen($pw) > 200 || strpos($pw, "\0") !== false) $r[] = 'too_long';
    return $r;
}

function tj_admin_perms(array $a): array {
    if ((int)$a['is_owner'] === 1) return TJ_ADMIN_PERMISSIONS;
    $p = json_decode((string)$a['permissions'], true);
    return is_array($p) ? array_values(array_intersect(TJ_ADMIN_PERMISSIONS, $p)) : [];
}

/* Only known permission names survive. */
function tj_admin_clean_perms($given): array {
    return is_array($given) ? array_values(array_intersect(TJ_ADMIN_PERMISSIONS, $given)) : [];
}

/* CSRF token = HMAC of the session token with the server key: nothing
 * extra to store, and only someone holding the cookie can know it. */
function tj_admin_csrf(string $token): string {
    return hash_hmac('sha256', 'admin-csrf|' . $token, base64_decode(tj_secrets()['enc_key']));
}

function tj_admin_set_cookie(string $value, int $expires): void {
    setcookie(TJ_ADMIN_COOKIE, $value, ['expires' => $expires, 'path' => '/', 'secure' => true, 'httponly' => true, 'samesite' => 'Strict']);
}

function tj_admin_start_session(array $a): array {
    $token = tj_random_token();
    tj_db()->prepare('INSERT INTO tj_admin_sessions (admin_id, token_hash, ip, user_agent, created_at, last_seen_at) VALUES (?, ?, ?, ?, ?, ?)')
        ->execute([$a['id'], tj_hash($token), tj_client_ip(), substr((string)($_SERVER['HTTP_USER_AGENT'] ?? ''), 0, 255), tj_now(), tj_now()]);
    tj_db()->prepare('UPDATE tj_admins SET failed_logins = 0, locked_until = NULL, last_login_at = ? WHERE id = ?')->execute([tj_now(), $a['id']]);
    tj_admin_set_cookie($token, 0); // a browser-session cookie; the server enforces the time limits
    return ['csrf' => tj_admin_csrf($token), 'email' => $a['email'], 'permissions' => tj_admin_perms($a), 'is_owner' => (int)$a['is_owner'] === 1];
}

function tj_admin_end_sessions(int $adminId): void {
    tj_db()->prepare('UPDATE tj_admin_sessions SET revoked_at = ? WHERE admin_id = ? AND revoked_at IS NULL')->execute([tj_now(), $adminId]);
}

/* The signed-in admin, or null. Mutating requests (anything but GET)
 * also need the CSRF header and a same-origin Origin. */
function tj_admin_current(bool $required = true): ?array {
    $token = (string)($_COOKIE[TJ_ADMIN_COOKIE] ?? '');
    $row = null;
    if ($token !== '') {
        $q = tj_db()->prepare('SELECT s.id AS session_id, s.created_at AS session_created, s.last_seen_at, a.*
                               FROM tj_admin_sessions s JOIN tj_admins a ON a.id = s.admin_id
                               WHERE s.token_hash = ? AND s.revoked_at IS NULL AND a.disabled_at IS NULL');
        $q->execute([tj_hash($token)]);
        $row = $q->fetch() ?: null;
        if ($row && ($row['last_seen_at'] < tj_now(-TJ_ADMIN_IDLE) || $row['session_created'] < tj_now(-TJ_ADMIN_MAX_AGE))) {
            tj_db()->prepare('UPDATE tj_admin_sessions SET revoked_at = ? WHERE id = ?')->execute([tj_now(), $row['session_id']]);
            $row = null;
        }
    }
    if (!$row) {
        if ($required) tj_fail(401, 'not_authenticated');
        return null;
    }
    if (($_SERVER['REQUEST_METHOD'] ?? 'GET') !== 'GET') {
        $origin = (string)($_SERVER['HTTP_ORIGIN'] ?? '');
        if ($origin !== '' && $origin !== 'https://' . ($_SERVER['HTTP_HOST'] ?? '')) tj_fail(403, 'bad_origin');
        if (!hash_equals(tj_admin_csrf($token), (string)($_SERVER['HTTP_X_CSRF_TOKEN'] ?? ''))) tj_fail(403, 'bad_csrf');
    }
    tj_db()->prepare('UPDATE tj_admin_sessions SET last_seen_at = ? WHERE id = ?')->execute([tj_now(), $row['session_id']]);
    $row['token'] = $token;
    return $row;
}

/* Signed in AND allowed to do $perm, else 401/403. */
function tj_admin_require(string $perm): array {
    tj_admin_gate();
    $a = tj_admin_current();
    if (!in_array($perm, tj_admin_perms($a), true)) tj_fail(403, 'forbidden');
    return $a;
}

function tj_admin_count(): int {
    return (int)tj_db()->query('SELECT COUNT(*) AS n FROM tj_admins')->fetch()['n'];
}

function tj_admin_find(string $publicId): array {
    $q = tj_db()->prepare('SELECT * FROM tj_admins WHERE public_id = ?');
    $q->execute([$publicId]);
    $a = $q->fetch();
    if (!$a) tj_fail(404, 'not_found');
    return $a;
}

function tj_admin_password(array $b): string {
    $password = is_string($b['password'] ?? null) ? $b['password'] : '';
    if ($problems = tj_admin_password_problems($password)) tj_fail(400, 'weak_password', ['reasons' => $problems]);
    return $password;
}

/* ---- sign-in endpoints ---- */

function tj_admin_state(): void {
    tj_admin_gate();
    $a = tj_admin_current(false);
    tj_json([
        'setup_needed' => tj_admin_count() === 0,
        'signed_in' => (bool)$a,
        'email' => $a['email'] ?? null,
        'permissions' => $a ? tj_admin_perms($a) : [],
        'is_owner' => $a ? (int)$a['is_owner'] === 1 : false,
        'csrf' => $a ? tj_admin_csrf($a['token']) : null,
        'all_permissions' => TJ_ADMIN_PERMISSIONS,
        'idle_seconds' => TJ_ADMIN_IDLE,
    ]);
}

function tj_admin_setup(): void {
    tj_admin_gate();
    tj_throttle('admin_setup', tj_client_ip(), 5, 3600);
    $b = tj_body();
    $s = tj_admin_settings();
    if (tj_admin_count() > 0 || !isset($s['setup_code'])) tj_fail(409, 'setup_closed');
    $code = strtoupper(str_replace([' ', '-'], '', tj_str($b, 'code', 60)));
    if (!hash_equals(str_replace('-', '', $s['setup_code']), $code)) {
        tj_admin_audit(null, 'setup_failed');
        tj_fail(403, 'bad_setup_code');
    }
    $email = strtolower(tj_str($b, 'email', 254));
    if (!tj_valid_email($email)) tj_fail(400, 'validation_error', ['fields' => ['email' => ['invalid']]]);
    $password = tj_admin_password($b);

    $db = tj_db();
    $db->prepare('INSERT INTO tj_admins (public_id, email, password_hash, is_owner, permissions, created_at) VALUES (?, ?, ?, 1, ?, ?)')
        ->execute([tj_new_public_id(), $email, password_hash($password, PASSWORD_DEFAULT), '[]', tj_now()]);
    $adminId = (int)$db->lastInsertId();
    unset($s['setup_code']);
    tj_admin_write_file($s); // the code is single-use
    tj_admin_audit($adminId, 'setup_done', $email);
    $q = $db->prepare('SELECT * FROM tj_admins WHERE id = ?');
    $q->execute([$adminId]);
    tj_json(tj_admin_start_session($q->fetch()), 201);
}

function tj_admin_login(): void {
    tj_admin_gate();
    $b = tj_body();
    $email = strtolower(tj_str($b, 'email', 254));
    $password = is_string($b['password'] ?? null) ? $b['password'] : '';
    tj_throttle('admin_login_ip', tj_client_ip(), 10, 900);
    tj_throttle('admin_login_email', $email, 5, 900);

    $db = tj_db();
    $q = $db->prepare('SELECT * FROM tj_admins WHERE email = ?');
    $q->execute([$email]);
    $a = $q->fetch() ?: null;
    // Same work and answer for unknown, disabled or not-yet-activated admins.
    $usable = $a && $a['password_hash'] !== '' && $a['disabled_at'] === null;
    $ok = password_verify($password, $usable ? $a['password_hash'] : tj_dummy_hash());
    if ($usable && $a['locked_until'] !== null && $a['locked_until'] > tj_now()) {
        tj_admin_audit((int)$a['id'], 'login_locked', $email);
        tj_fail(429, 'locked');
    }
    if (!$usable || !$ok) {
        if ($usable) {
            $fails = (int)$a['failed_logins'] + 1;
            $db->prepare('UPDATE tj_admins SET failed_logins = ?, locked_until = ? WHERE id = ?')
                ->execute([$fails >= TJ_ADMIN_MAX_FAILS ? 0 : $fails, $fails >= TJ_ADMIN_MAX_FAILS ? tj_now(TJ_ADMIN_LOCK) : null, $a['id']]);
        }
        tj_admin_audit($a ? (int)$a['id'] : null, 'login_failed', $email);
        tj_fail(401, 'invalid_credentials');
    }
    if (password_needs_rehash($a['password_hash'], PASSWORD_DEFAULT)) {
        $db->prepare('UPDATE tj_admins SET password_hash = ? WHERE id = ?')->execute([password_hash($password, PASSWORD_DEFAULT), $a['id']]);
    }
    $out = tj_admin_start_session($a);
    tj_admin_audit((int)$a['id'], 'login_ok', $email);
    tj_json($out);
}

/* A new admin: email + invite code + their own password. */
function tj_admin_accept_invite(): void {
    tj_admin_gate();
    tj_throttle('admin_invite_ip', tj_client_ip(), 10, 3600);
    $b = tj_body();
    $email = strtolower(tj_str($b, 'email', 254));
    $code = strtoupper(str_replace([' ', '-'], '', tj_str($b, 'code', 60)));
    $q = tj_db()->prepare('SELECT * FROM tj_admins WHERE email = ? AND invite_hash IS NOT NULL AND disabled_at IS NULL');
    $q->execute([$email]);
    $a = $q->fetch() ?: null;
    if (!$a || $a['invite_expires'] <= tj_now() || !hash_equals($a['invite_hash'], tj_hash($code))) {
        tj_admin_audit($a ? (int)$a['id'] : null, 'invite_failed', $email);
        tj_fail(403, 'bad_invite');
    }
    $password = tj_admin_password($b);
    tj_db()->prepare('UPDATE tj_admins SET password_hash = ?, invite_hash = NULL, invite_expires = NULL WHERE id = ?')
        ->execute([password_hash($password, PASSWORD_DEFAULT), $a['id']]);
    $a['password_hash'] = 'set';
    tj_admin_audit((int)$a['id'], 'invite_accepted', $email);
    tj_json(tj_admin_start_session($a), 201);
}

function tj_admin_logout(): void {
    tj_admin_gate();
    $a = tj_admin_current();
    tj_db()->prepare('UPDATE tj_admin_sessions SET revoked_at = ? WHERE id = ?')->execute([tj_now(), $a['session_id']]);
    tj_admin_set_cookie('', time() - 3600);
    tj_admin_audit((int)$a['id'], 'logout');
    tj_json(['ok' => true]);
}

