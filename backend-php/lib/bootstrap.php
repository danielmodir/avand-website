<?php
/* Toojibee PHP API — core: config, database, schema, JSON helpers.
 *
 * Why PHP: the live host (shared cPanel) runs PHP + MySQL but not Python,
 * so the Django backend (backend/) can't run there. This is a small API
 * with the same auth contract the app already speaks, plus one "sync"
 * document per account. See backend-php/README.md.
 *
 * Secrets never live in the web root or in git:
 *   ~/toojibee-data/        SQLite database, the default (no setup)
 *   ~/toojibee-config.php   optional: MySQL credentials instead
 *   ~/toojibee-secrets.php  encryption key, generated here on first use
 * (~ = the account home, one level above public_html.) For local tests
 * TJ_CONFIG / TJ_SECRETS env vars point elsewhere.
 */
declare(strict_types=1);

const TJ_ACCESS_TTL  = 3600;            // 1 hour
const TJ_REFRESH_TTL = 60 * 86400;      // 60 days
const TJ_MAX_SYNC_BYTES = 3 * 1024 * 1024;
const TJ_MIN_PASSWORD = 8;

function tj_home(): string {
    // .../public_html/api/lib -> .../ (the account home)
    return dirname(__DIR__, 3);
}

function tj_config(): array {
    static $cfg = null;
    if ($cfg !== null) return $cfg;
    $path = getenv('TJ_CONFIG') ?: tj_home() . '/toojibee-config.php';
    // No config file: a SQLite database in ~/toojibee-data/ (outside the
    // web root). Works with no setup and no DB password; a config file
    // with MySQL credentials takes over when there is one.
    $cfg = is_file($path) ? require $path : ['db_dsn' => 'sqlite:' . tj_data_dir() . '/toojibee.sqlite'];
    $cfg += [
        'app_url'   => 'https://toojibee.ir/demo/',
        'mail_from' => 'Toojibee <no-reply@toojibee.ir>',
        'send_mail' => true,
    ];
    return $cfg;
}

function tj_data_dir(): string {
    $dir = getenv('TJ_DATA_DIR') ?: tj_home() . '/toojibee-data';
    if (!is_dir($dir) && !@mkdir($dir, 0700, true)) tj_fail(500, 'data_dir_unwritable');
    return $dir;
}

/* A random 32-byte key, created once, outside the web root, readable
 * only by this account. Used to encrypt period data at rest. */
function tj_secrets(): array {
    static $sec = null;
    if ($sec !== null) return $sec;
    $path = getenv('TJ_SECRETS') ?: tj_home() . '/toojibee-secrets.php';
    if (!is_file($path)) {
        $data = ['enc_key' => base64_encode(random_bytes(32))];
        $php = "<?php\n// Generated by the Toojibee API on first use. Never share or commit.\nreturn " . var_export($data, true) . ";\n";
        if (@file_put_contents($path, $php, LOCK_EX) === false) tj_fail(500, 'secrets_unwritable');
        @chmod($path, 0600);
    }
    $sec = require $path;
    return $sec;
}

function tj_db(): PDO {
    static $db = null;
    if ($db !== null) return $db;
    $c = tj_config();
    $db = new PDO($c['db_dsn'], $c['db_user'] ?? null, $c['db_pass'] ?? null, [
        PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
        PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
        PDO::ATTR_EMULATE_PREPARES => false,
    ]);
    if (tj_driver() === 'sqlite') {
        $db->exec('PRAGMA foreign_keys = ON');
        $db->exec('PRAGMA busy_timeout = 5000'); // wait, don't fail, when two requests write at once
        $db->exec('PRAGMA journal_mode = WAL');
    }
    tj_migrate($db);
    return $db;
}

function tj_driver(): string {
    return strpos(tj_config()['db_dsn'], 'sqlite:') === 0 ? 'sqlite' : 'mysql';
}

/* Tables are created on the first request (no SSH / phpMyAdmin needed).
 * schema_version lets later versions add migrations safely. */
function tj_migrate(PDO $db): void {
    $sqlite = tj_driver() === 'sqlite';
    $id = $sqlite ? 'INTEGER PRIMARY KEY AUTOINCREMENT' : 'BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY';
    $fk = $sqlite ? 'INTEGER' : 'BIGINT UNSIGNED';
    $tail = $sqlite ? '' : ' ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci';
    $text = $sqlite ? 'TEXT' : 'MEDIUMTEXT';

    $db->exec("CREATE TABLE IF NOT EXISTS tj_schema (version INT NOT NULL)$tail");
    $v = (int)($db->query('SELECT MAX(version) AS v FROM tj_schema')->fetch()['v'] ?? 0);
    if ($v < 1) tj_migrate_v1($db, $id, $fk, $tail, $text, $sqlite);
    if ($v < 2) {
        // Sign-up asks for a username (instead of a real name), gender and
        // birth date. Accounts made before this have them empty.
        // Each step tolerates having been done already (two first
        // requests racing each other).
        foreach ([
            'ALTER TABLE tj_users ADD COLUMN username VARCHAR(30) NULL',
            'ALTER TABLE tj_users ADD COLUMN gender VARCHAR(10) NULL',
            'ALTER TABLE tj_users ADD COLUMN birth_date DATE NULL',
            'CREATE UNIQUE INDEX tj_users_username ON tj_users (username)',
        ] as $sql) {
            try { $db->exec($sql); } catch (PDOException $e) { /* already there */ }
        }
        $db->exec('INSERT INTO tj_schema (version) VALUES (2)');
    }
    if ($v < 3) tj_migrate_v3($db, $id, $fk, $tail, $sqlite);
    if ($v < 4) {
        // Presence for the admin panel: the app sends a heartbeat every
        // minute while it's open (POST /me/heartbeat). last_seen_at gives
        // "online now", active_seconds the total time spent in the app.
        foreach ([
            'ALTER TABLE tj_users ADD COLUMN last_seen_at DATETIME NULL',
            'ALTER TABLE tj_users ADD COLUMN active_seconds INT NOT NULL DEFAULT 0',
            'CREATE INDEX tj_users_last_seen ON tj_users (last_seen_at)',
        ] as $sql) {
            try { $db->exec($sql); } catch (PDOException $e) { /* already there */ }
        }
        $db->exec('INSERT INTO tj_schema (version) VALUES (4)');
    }
    if ($v < 5) {
        // Site content edited in the admin panel (lib/content.php).
        $db->exec("CREATE TABLE IF NOT EXISTS tj_content (
            name VARCHAR(40) NOT NULL PRIMARY KEY,
            value $text NOT NULL,
            updated_at DATETIME NOT NULL,
            updated_by $fk NULL
        )$tail");
        $db->exec('INSERT INTO tj_schema (version) VALUES (5)');
    }
    if ($v < 6) {
        // Articles written and reviewed in the admin panel (lib/articles.php).
        $db->exec("CREATE TABLE IF NOT EXISTS tj_articles (
            id $id,
            public_id CHAR(32) NOT NULL UNIQUE,
            lang VARCHAR(2) NOT NULL,
            slug VARCHAR(80) NOT NULL,
            title VARCHAR(160) NOT NULL,
            summary VARCHAR(300) NOT NULL DEFAULT '',
            body $text NOT NULL,
            cover VARCHAR(80) NULL,
            status VARCHAR(12) NOT NULL DEFAULT 'draft',
            review_note VARCHAR(500) NULL,
            author_id $fk NULL,
            reviewer_id $fk NULL,
            created_at DATETIME NOT NULL,
            updated_at DATETIME NOT NULL,
            submitted_at DATETIME NULL,
            published_at DATETIME NULL,
            UNIQUE (lang, slug)
        )$tail");
        try { $db->exec('CREATE INDEX tj_articles_list ON tj_articles (lang, status, published_at)'); } catch (PDOException $e) { /* already there */ }
        $db->exec('INSERT INTO tj_schema (version) VALUES (6)');
    }
}

/* v3: random account ids, and the admin panel's own tables.
 * The numeric id stays internal (foreign keys); what leaves the server
 * is public_id (128 random bits) and display_id (8 random characters,
 * shown as TJ-XXXXXXXX) — neither says when or in what order an account
 * was made. Existing accounts get theirs here. */
function tj_migrate_v3(PDO $db, string $id, string $fk, string $tail, bool $sqlite): void {
    foreach ([
        'ALTER TABLE tj_users ADD COLUMN public_id CHAR(32) NULL',
        'ALTER TABLE tj_users ADD COLUMN display_id VARCHAR(8) NULL',
        'CREATE UNIQUE INDEX tj_users_public_id ON tj_users (public_id)',
        'CREATE UNIQUE INDEX tj_users_display_id ON tj_users (display_id)',
    ] as $sql) {
        try { $db->exec($sql); } catch (PDOException $e) { /* already there */ }
    }
    foreach ($db->query('SELECT id FROM tj_users WHERE public_id IS NULL')->fetchAll() as $row) {
        $db->prepare('UPDATE tj_users SET public_id = ?, display_id = ? WHERE id = ?')
            ->execute([tj_new_public_id(), tj_new_display_id($db), $row['id']]);
    }
    // is_owner: the first admin, has every permission and can't be
    // changed by others. permissions: JSON list (lib/admin.php
    // TJ_ADMIN_PERMISSIONS). A new admin starts with an invite (hash
    // only) and sets their own password; password_hash is '' until then.
    $db->exec("CREATE TABLE IF NOT EXISTS tj_admins (
        id $id,
        public_id CHAR(32) NOT NULL UNIQUE,
        email VARCHAR(254) NOT NULL UNIQUE,
        password_hash VARCHAR(255) NOT NULL DEFAULT '',
        is_owner INT NOT NULL DEFAULT 0,
        permissions TEXT NOT NULL,
        invite_hash CHAR(64) NULL,
        invite_expires DATETIME NULL,
        disabled_at DATETIME NULL,
        created_by $fk NULL,
        failed_logins INT NOT NULL DEFAULT 0,
        locked_until DATETIME NULL,
        last_login_at DATETIME NULL,
        created_at DATETIME NOT NULL
    )$tail");
    $db->exec("CREATE TABLE IF NOT EXISTS tj_admin_sessions (
        id $id,
        admin_id $fk NOT NULL,
        token_hash CHAR(64) NOT NULL UNIQUE,
        ip VARCHAR(45) NOT NULL DEFAULT '',
        user_agent VARCHAR(255) NOT NULL DEFAULT '',
        created_at DATETIME NOT NULL,
        last_seen_at DATETIME NOT NULL,
        revoked_at DATETIME NULL,
        FOREIGN KEY (admin_id) REFERENCES tj_admins(id) ON DELETE CASCADE
    )$tail");
    // Append-only: nothing in the API updates or deletes these rows.
    $db->exec("CREATE TABLE IF NOT EXISTS tj_admin_audit (
        id $id,
        admin_id $fk NULL,
        action VARCHAR(40) NOT NULL,
        detail VARCHAR(500) NOT NULL DEFAULT '',
        ip VARCHAR(45) NOT NULL DEFAULT '',
        created_at DATETIME NOT NULL
    )$tail");
    $db->exec('INSERT INTO tj_schema (version) VALUES (3)');
    // Creates ~/toojibee-admin.php (panel address + one-time setup code)
    // right away, so the owner can find it in File Manager.
    if (function_exists('tj_admin_settings')) tj_admin_settings();
}

/* ---- random ids ---- */

// Crockford base32: no I, L, O, U, so a shared code can't be misread.
const TJ_CODE_ALPHABET = '0123456789ABCDEFGHJKMNPQRSTVWXYZ';

function tj_random_code(int $len): string {
    $s = '';
    for ($i = 0; $i < $len; $i++) $s .= TJ_CODE_ALPHABET[random_int(0, 31)];
    return $s;
}

function tj_new_public_id(): string {
    return bin2hex(random_bytes(16));
}

function tj_new_display_id(PDO $db): string {
    $q = $db->prepare('SELECT 1 FROM tj_users WHERE display_id = ?');
    do { $code = tj_random_code(8); $q->execute([$code]); } while ($q->fetch());
    return $code;
}

function tj_migrate_v1(PDO $db, string $id, string $fk, string $tail, string $text, bool $sqlite): void {

    $db->exec("CREATE TABLE IF NOT EXISTS tj_users (
        id $id,
        email VARCHAR(254) NOT NULL UNIQUE,
        password_hash VARCHAR(255) NOT NULL,
        first_name VARCHAR(60) NOT NULL DEFAULT '',
        last_name VARCHAR(60) NOT NULL DEFAULT '',
        email_verified_at DATETIME NULL,
        status VARCHAR(16) NOT NULL DEFAULT 'active',
        created_at DATETIME NOT NULL,
        updated_at DATETIME NOT NULL
    )$tail");
    $db->exec("CREATE TABLE IF NOT EXISTS tj_sessions (
        id $id,
        user_id $fk NOT NULL,
        access_hash CHAR(64) NOT NULL UNIQUE,
        refresh_hash CHAR(64) NOT NULL UNIQUE,
        access_expires DATETIME NOT NULL,
        refresh_expires DATETIME NOT NULL,
        user_agent VARCHAR(255) NOT NULL DEFAULT '',
        created_at DATETIME NOT NULL,
        last_used_at DATETIME NOT NULL,
        revoked_at DATETIME NULL,
        FOREIGN KEY (user_id) REFERENCES tj_users(id) ON DELETE CASCADE
    )$tail");
    $db->exec("CREATE TABLE IF NOT EXISTS tj_tokens (
        id $id,
        user_id $fk NOT NULL,
        purpose VARCHAR(16) NOT NULL,
        token_hash CHAR(64) NOT NULL UNIQUE,
        expires_at DATETIME NOT NULL,
        used_at DATETIME NULL,
        created_at DATETIME NOT NULL,
        FOREIGN KEY (user_id) REFERENCES tj_users(id) ON DELETE CASCADE
    )$tail");
    $db->exec("CREATE TABLE IF NOT EXISTS tj_user_data (
        user_id $fk NOT NULL PRIMARY KEY,
        data $text NOT NULL,
        version INT NOT NULL DEFAULT 0,
        updated_at DATETIME NOT NULL,
        FOREIGN KEY (user_id) REFERENCES tj_users(id) ON DELETE CASCADE
    )$tail");
    $db->exec("CREATE TABLE IF NOT EXISTS tj_attempts (
        id $id,
        kind VARCHAR(16) NOT NULL,
        key_hash CHAR(64) NOT NULL,
        created_at DATETIME NOT NULL
    )$tail");
    $db->exec('CREATE INDEX ' . ($sqlite ? 'IF NOT EXISTS ' : '') . 'tj_attempts_lookup ON tj_attempts (kind, key_hash, created_at)');
    $db->exec('INSERT INTO tj_schema (version) VALUES (1)');
}

/* ---- request / response helpers ---- */

function tj_now(int $plusSeconds = 0): string {
    return gmdate('Y-m-d H:i:s', time() + $plusSeconds);
}

function tj_json($data, int $status = 200): void {
    http_response_code($status);
    header('Content-Type: application/json; charset=utf-8');
    header('Cache-Control: no-store');
    header('X-Content-Type-Options: nosniff');
    echo json_encode($data, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES);
    exit;
}

/* Same {"error": code} shape as the Django API, so the app's
 * authErrorMessage() maps it to the same messages. */
function tj_fail(int $status, string $code, array $extra = []): void {
    tj_json(['error' => $code] + $extra, $status);
}

function tj_body(): array {
    $raw = file_get_contents('php://input') ?: '';
    if (strlen($raw) > TJ_MAX_SYNC_BYTES + 65536) tj_fail(413, 'too_large');
    if ($raw === '') return [];
    $data = json_decode($raw, true);
    if (!is_array($data)) tj_fail(400, 'invalid_json');
    return $data;
}

function tj_str(array $body, string $key, int $max = 255): string {
    $v = $body[$key] ?? '';
    if (!is_string($v)) return '';
    $v = trim($v);
    return function_exists('mb_substr') ? mb_substr($v, 0, $max) : substr($v, 0, $max);
}

function tj_client_ip(): string {
    return $_SERVER['REMOTE_ADDR'] ?? '0.0.0.0';
}

function tj_random_token(): string {
    return rtrim(strtr(base64_encode(random_bytes(32)), '+/', '-_'), '=');
}

/* A real bcrypt hash of a random hex string, for checking a password
 * against when the account doesn't exist (same timing either way). Hex,
 * not raw bytes: bcrypt in PHP 8.3+ throws on a NUL byte, which raw
 * random bytes contain now and then (that was a 500 on ~6% of sign-ins
 * with an unknown email). */
function tj_dummy_hash(): string {
    static $h = null;
    return $h ?? ($h = password_hash(bin2hex(random_bytes(16)), PASSWORD_DEFAULT));
}

function tj_hash(string $token): string {
    return hash('sha256', $token);
}

/* Simple sliding-window limit: at most $max events of $kind for $key in
 * $windowSeconds. Old rows are pruned as we go. */
function tj_throttle(string $kind, string $key, int $max, int $windowSeconds): void {
    $db = tj_db();
    $h = tj_hash($kind . '|' . $key);
    $db->prepare('DELETE FROM tj_attempts WHERE created_at < ?')->execute([tj_now(-86400)]);
    $q = $db->prepare('SELECT COUNT(*) AS n FROM tj_attempts WHERE kind = ? AND key_hash = ? AND created_at >= ?');
    $q->execute([$kind, $h, tj_now(-$windowSeconds)]);
    if ((int)$q->fetch()['n'] >= $max) tj_fail(429, 'throttled');
    $db->prepare('INSERT INTO tj_attempts (kind, key_hash, created_at) VALUES (?, ?, ?)')->execute([$kind, $h, tj_now()]);
}

/* ---- encryption at rest (period data) ---- */

function tj_encrypt(string $plain): string {
    $key = base64_decode(tj_secrets()['enc_key']);
    $iv = random_bytes(12);
    $tag = '';
    $ct = openssl_encrypt($plain, 'aes-256-gcm', $key, OPENSSL_RAW_DATA, $iv, $tag);
    if ($ct === false) tj_fail(500, 'encryption_failed');
    return base64_encode($iv . $tag . $ct);
}

function tj_decrypt(string $blob): ?string {
    $raw = base64_decode($blob, true);
    if ($raw === false || strlen($raw) < 29) return null;
    $key = base64_decode(tj_secrets()['enc_key']);
    $plain = openssl_decrypt(substr($raw, 28), 'aes-256-gcm', $key, OPENSSL_RAW_DATA, substr($raw, 0, 12), substr($raw, 12, 16));
    return $plain === false ? null : $plain;
}
